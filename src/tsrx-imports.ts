/** Typed `.tsrx` compose imports for authored `.tsx`: the generated `tsrx-imports.d.ts` ambient typings, written by the corpus compile so tsc can check a `.tsx` parent's compose import of a `.tsrx` child. */

/* === Types === */

export type TsrxImportSource = {
	/** Authored `.tsrx` path, relative to the project root. */
	source: string
	/** Component function name (`BasicButton`). */
	name: string
	/** Generated server module, relative to the output root. */
	serverModule: string
	/** Slot-backed exposed props — the keys a `truc:pass` may replace. */
	passProps?: readonly string[]
}

export type TsrxTagMapEntry = {
	/** Custom element tag (`basic-button`). */
	tag: string
	/** Generated client module, relative to the output root. */
	clientModule: string
	/** The client's exported `<Name>Props` type, when authored. */
	propsType: string | null
	/** `FormAssociatedElement` host instead of `HTMLElement`. */
	formAssociated: boolean
}

/* === Exported Constants === */

/** The generated typings file, written into the output root. */
export const TSRX_IMPORTS_FILE = 'tsrx-imports.d.ts'

/** Where the generated clients import the library from. */
const LIBRARY_IMPORT = '@zeix/le-truc'

/* === Internal Functions === */

const uniqueSuffix = (source: string, others: readonly string[]): string => {
	const segments = source.split('/')
	for (let k = 1; k <= segments.length; k++) {
		const suffix = segments.slice(-k).join('/')
		if (!others.some(o => o === suffix || o.endsWith(`/${suffix}`)))
			return suffix
	}
	return source
}

/* === Exported Functions === */

export const tsrxImportTypings = (
	sources: readonly TsrxImportSource[],
	tags: readonly TsrxTagMapEntry[] = [],
): string => {
	const entries = sources
		.map(entry => ({
			entry,
			pattern: `*/${uniqueSuffix(
				entry.source,
				sources.filter(o => o !== entry).map(o => o.source),
			)}`,
		}))
		.sort((a, b) => a.pattern.localeCompare(b.pattern))
	const lines = [
		'/**',
		' * Generated by the Le Truc corpus compile (LT-312) — DO NOT EDIT.',
		' * Types every compiled `.tsrx` source for compose imports from authored',
		' * `.tsx`, through its generated server module, and every `.tsrx`-served',
		' * tag for `first`/`all` queries, through its generated client (LT-325;',
		' * `tsrx-imports.ts`).',
		' */',
	]
	if (tags.length > 0) {
		lines.push('', 'interface HTMLElementTagNameMap {')
		for (const entry of [...tags].sort((a, b) => a.tag.localeCompare(b.tag))) {
			const host = entry.formAssociated
				? `import('${LIBRARY_IMPORT}').FormAssociatedElement`
				: 'HTMLElement'
			const module = `./${entry.clientModule.replace(/\.ts$/, '')}`
			const props = entry.propsType
				? ` & import('${module}').${entry.propsType}`
				: ''
			lines.push(`\t${JSON.stringify(entry.tag)}: ${host}${props}`)
		}
		lines.push('}')
	}
	for (const { entry, pattern } of entries) {
		const module = `./${entry.serverModule.replace(/\.ts$/, '')}`
		const pass = [...(entry.passProps ?? [])].sort()
		const passLines =
			pass.length === 0
				? []
				: [
						"\t\t\t'truc:pass'?: {",
						...pass.map(
							prop => `\t\t\t\t${JSON.stringify(prop)}?: JSX.PassEntry`,
						),
						'\t\t\t}',
					]
		lines.push(
			'',
			`declare module '${pattern}' {`,
			`\texport const ${entry.name}: (`,
			'\t\targs: Parameters<',
			`\t\t\ttypeof import('${module}').render${entry.name}`,
			pass.length === 0 ? '\t\t>[0],' : '\t\t>[0] & {',
			...passLines,
			...(pass.length === 0 ? [] : ['\t\t},']),
			'\t) => JSX.Element',
			'}',
		)
	}
	return `${lines.join('\n')}\n`
}
